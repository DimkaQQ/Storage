// Какие склады iiko берём: только кухонные. Склады бара, хозтоваров, посуды, кальяна, инвентаря, витрины, упаковки —
// не еда, их не показываем (решение заказчика). Правило одно и видимое: в названии склада есть слово «кухня» (или «цех») — берём;
// есть слово отдела без «кухни» — не берём; названия без отдела (например «Рене», «Акку») не трогаем.
// Короткие слова отделов сравниваются целиком (чтобы «Барашек» не считался баром), длинные — по началу слова.
const EXACT = new Set(['бар', 'хоз', 'зал', 'общая', 'товары', 'товар', 'тов'])
const PREFIX = ['посуд', 'кальян', 'инвентар', 'витрин', 'упаков', 'одноразов', 'заготочн']
const tokens = (name) => String(name || '').toLowerCase().split(/[\s/.,()\-]+/).filter(Boolean)

export function isKitchenStore(name) {
  const t = tokens(name)
  if (t.some((w) => w.startsWith('кухн') || w === 'цех')) return true
  return !t.some((w) => EXACT.has(w) || PREFIX.some((s) => w.startsWith(s)))
}
