// Какие склады iiko берём: только кухонные. Склады бара, хозтоваров, посуды, кальяна, инвентаря, витрины, упаковки —
// не еда, их не показываем (решение заказчика). Правило одно и видимое:
//  - «сильные» слова отделов (инвентарь, посуда, кальян, витрина, упаковка, хозтовары…) — склад не берём, даже если есть слово «кухня» («Инвентарь кухня»);
//  - «слабые» слова (бар, зал, общая, товары) — не берём, только если слова «кухня»/«цех» в названии нет («Бар-кухня» остаётся);
//  - всё остальное («Кухня склад Олово», «Склад Кухня Танжир», «Рене») берём.
// Короткие слова сравниваются целиком (чтобы «Барашек» не считался баром), длинные — по началу слова.
const STRONG_PREFIX = ['посуд', 'кальян', 'инвентар', 'витрин', 'упаков', 'одноразов', 'хозтов']
const STRONG_EXACT = new Set(['хоз'])
const WEAK_EXACT = new Set(['бар', 'зал', 'общая', 'товары', 'товар', 'тов'])
const tokens = (name) => String(name || '').toLowerCase().split(/[\s/.,()\-]+/).filter(Boolean)

export function isKitchenStore(name) {
  const t = tokens(name)
  if (t.some((w) => STRONG_EXACT.has(w) || STRONG_PREFIX.some((s) => w.startsWith(s)))) return false
  if (t.some((w) => w.startsWith('кухн') || w === 'цех')) return true
  return !t.some((w) => WEAK_EXACT.has(w))
}
